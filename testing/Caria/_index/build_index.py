#!/usr/bin/env python3
"""build_index.py -- rebuild testing/Caria/00 INDEX - Caria Playtest.md

Usage (from the repo root or anywhere):
    python testing/Caria/_index/build_index.py

What it does:
  1. Lists every file in testing/Caria by session and by type, from the file names.
  2. Reads _index/names.tsv (the editable name list) and, for each name, finds
     which files mention it -- matching the name as written OR in ALL CAPS
     (the ledgers capitalise names), on word boundaries.
  3. Writes "00 INDEX - Caria Playtest.md" beside the files. ASCII only.

To add someone or somewhere: add a line to names.tsv and rerun. Nothing else
needs touching. The index is a finding aid, not canon (see names.tsv header).
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent                      # testing/Caria
OUT = ROOT / "00 INDEX - Caria Playtest.md"
NAMES = HERE / "names.tsv"

TYPES = [  # (label, test on the file name) -- first match wins
    ("Transcript", lambda n: "TRANSCRIPT" in n),
    ("Ledger", lambda n: "Ledger" in n),
    ("Resume brief", lambda n: "Resume Brief" in n),
    ("Who Knows What", lambda n: "Who Knows What" in n),
    ("Handoff", lambda n: "HANDOFF" in n),
    ("Gap log", lambda n: "Gap Log" in n),
    ("Session summary", lambda n: "SESSION" in n),
    ("Character", lambda n: "CHARACTER" in n),
    ("Cast", lambda n: "CAST" in n or "Cast Card" in n or "NPC Frames" in n),
    ("Setting", lambda n: "SETTING" in n or "Book of Days" in n),
    ("Lore", lambda n: "LORE" in n),
    ("Prep", lambda n: "PREP" in n),
    ("Design note", lambda n: "DESIGN NOTE" in n),
    ("Index", lambda n: "README" in n or n.startswith("00 INDEX")),
    ("Tool", lambda n: n.endswith(".sh")),
]

SESSION_RE = re.compile(r"\bS(\d{1,2})(?:\s+Part\s+(\d))?\b")


def ftype(name):
    for label, test in TYPES:
        if test(name):
            return label
    return "Other"


def session(name):
    """Return (sort key, label) for the session a file belongs to."""
    if "cumulative S1-S" in name:
        m = re.search(r"cumulative S1-S(\d+)", name)
        return (int(m.group(1)) + 0.9, "S1-S%s (cumulative)" % m.group(1))
    m = SESSION_RE.search(name)
    if not m:
        return (99, "--")
    n = int(m.group(1))
    part = m.group(2)
    if part:
        return (n + int(part) / 10.0, "S%02d Part %s" % (n, part))
    return (float(n), "S%02d" % n)


def date(name):
    m = re.match(r"(\d{4}-\d{2}-\d{2})", name)
    return m.group(1) if m else ""


def load_names():
    rows = []
    for line in NAMES.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cols = (line.split("\t") + [""] * 5)[:5]
        name, aliases, kind, region, note = [c.strip() for c in cols]
        forms = [name] + [a.strip() for a in aliases.split(",") if a.strip()]
        rows.append(dict(name=name, forms=forms, kind=kind, region=region, note=note))
    return rows


def pattern(forms):
    alts = []
    for f in forms:
        for v in {f, f.upper()}:
            alts.append(r"\b" + re.escape(v) + r"\b")
    return re.compile("|".join(alts))


def main():
    files = sorted(p for p in ROOT.iterdir() if p.is_file() and p.name != OUT.name)
    texts = {p.name: p.read_text(encoding="utf-8", errors="replace") for p in files}
    info = {p.name: (ftype(p.name), session(p.name), date(p.name)) for p in files}

    L = []
    L.append("# 00 INDEX - Caria Playtest (files and setting)")
    L.append("")
    L.append("GENERATED by `_index/build_index.py` -- do not hand-edit; edit `_index/names.tsv` and rerun.")
    L.append("Files marked GM ONLY hold spoilers. The setting index below is a FINDING AID, not canon:")
    L.append("its notes summarise the record (most details there are @@* GM invention unless tagged [Lee]).")
    L.append("Always check the source file before relying on a detail.")
    L.append("")

    handoffs = sorted((info[n][1][0], n) for n in texts if info[n][0] == "Handoff")
    if handoffs:
        L.append("## Start here")
        L.append("")
        L.append("Latest handoff: `%s`" % handoffs[-1][1])
        L.append("")

    L.append("## Files by session")
    L.append("")
    L.append("| Session | Type | Date | File |")
    L.append("|---|---|---|---|")
    for n in sorted(texts, key=lambda n: (info[n][1][0], info[n][0], n)):
        t, (k, lab), d = info[n]
        L.append("| %s | %s | %s | %s |" % (lab, t, d, n))
    L.append("")

    L.append("## Setting index: people, spirits and places")
    L.append("")
    L.append("Mentions are counted per file, matching the name as written or in ALL CAPS.")
    L.append("Names flagged AMBIGUOUS in the note are shared by two people; the counts mix them.")
    L.append("")
    rows = load_names()
    regions = []
    for r in rows:
        if r["region"] not in regions:
            regions.append(r["region"])
    for reg in regions:
        L.append("### %s" % reg)
        L.append("")
        L.append("| Name | Kind | Note | First seen | Ledgers that mention it | Other files |")
        L.append("|---|---|---|---|---|---|")
        for r in [x for x in rows if x["region"] == reg]:
            pat = pattern(r["forms"])
            hits = [n for n in texts if pat.search(texts[n])]
            dated = sorted((info[n][2] or "9999", n) for n in hits if info[n][2])
            first = info[dated[0][1]][1][1] if dated else "--"
            ledg = sorted({info[n][1] for n in hits if info[n][0] == "Ledger"})
            ledg_s = ", ".join(lab for _, lab in ledg) or "--"
            other = sorted({info[n][0] for n in hits if info[n][0] not in ("Ledger", "Transcript")})
            if any(info[n][0] == "Transcript" for n in hits):
                other.append("Transcript")
            name = r["name"] + (" (%s)" % ", ".join(r["forms"][1:]) if len(r["forms"]) > 1 else "")
            L.append("| %s | %s | %s | %s | %s | %s |" % (
                name, r["kind"], r["note"].replace("|", "/"), first, ledg_s, ", ".join(other) or "--"))
        L.append("")

    out = "\n".join(L) + "\n"
    out = out.encode("ascii", "replace").decode("ascii")
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print("wrote", OUT, "--", len(texts), "files,", len(rows), "names")


if __name__ == "__main__":
    main()
